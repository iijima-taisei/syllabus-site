def N(s):
    return unicodedata.normalize("NFKC", s)


def pages(pdf):
    import pdfplumber
    with pdfplumber.open(pdf) as p:
        return [N(pg.extract_text() or "") for pg in p.pages]


def parse(text):
    head = text.split("\n")[1].strip()
    grads = [float(x) for x in re.findall(r"卒業要件:([\d.]+)単位】", text)]
    kt = re.search(r"基幹教育科目では,卒業要件として.*?([\d.]+)単位以上", text)
    y1 = re.search(r"1年次において([\d.]+)単位を修得", text)
    sk = re.search(r"2\.専攻教育科目\n専攻教育科目では,卒業要件として(?:I~V群が定める)?([\d.]+)(?:~([\d.]+))?単位", text)
    secs = {}
    for no, title, body in re.findall(r"\n\((\d+)\)([^\n]+)\n(.*?)(?=\n\(\d+\)|\n2\.専攻教育科目)", text, re.S):
        secs.setdefault(title.strip(), body.replace("\n", ""))
    return head, grads, kt and float(kt.group(1)), y1 and float(y1.group(1)), sk, secs


def build(pdf):
    P = pages(pdf)
    starts = [i for i, t in enumerate(P) if "1.基幹教育科目\n基幹教育科目では" in t]
    out = []
    for head0, name, cid, cls in COURSES:
        i = next((i for i in starts if P[i].split("\n")[1].strip().startswith(head0)
                  and (head0 != "文学部" or "国際" not in P[i].split("\n")[1])), None)
        if i is None:
            sys.exit(f"要項に見つかりません: {head0}")
        text = P[i] + ("\n" + P[i + 1] if "基幹教育科目では" not in P[i + 1] and "履修細目一覧" not in P[i + 1][:200] else "")
        head, grads, kiban, y1, sk, secs = parse(text)
        ov = OVERRIDE.get(cid, {})
        kiban = ov.get("kiban", kiban)
        groups = []
        for gid, gname, key, match in GROUPS:
            if gid in ("kb-en", "kb-l2"):
                body = next(b for t, b in secs.items() if t.startswith("言語文化"))
                nums = [float(x) for x in re.findall(r"([\d.]+)単位以上", body)]
                en, l2 = (nums[0], nums[2]) if "10月入学生" in body else ((nums[1], nums[2]) if len(nums) >= 3 else (nums[0], nums[1]))
                req = en if gid == "kb-en" else l2
            else:
                body = next((b for t, b in secs.items() if t.startswith(key)), None)
                if body is None:
                    continue
                m = re.search(r"([\d.]+)単位以上", body) or re.search(r"\(([\d.]+)単位\)", body)
                req = float(m.group(1))
            req = ov.get(gid, req)
            g = {"id": gid, "name": gname, "req": req}
            if match:
                g["match"] = match
            if gid in BYNAME:
                g["byName"] = BYNAME[gid]
            groups.append(g)
        other = next((b for t, b in secs.items() if t.startswith("その他")), None)
        if other:
            groups.append({"id": "kb-ot", "name": "その他", "req": float(re.search(r"([\d.]+)単位以上", other).group(1)), "other": True})
        s = sum(g["req"] for g in groups)
        if abs(s - kiban) > 1e-9:
            sys.exit(f"{name}: 区分の合計 {s} が基幹教育の単位数 {kiban} と合いません")
        total = grads[0] if len(grads) == 1 else None
        senkou = float(sk.group(1)) if sk and not sk.group(2) else None
        if total is not None and senkou is not None and abs(kiban + senkou - total) > 1e-9:
            sys.exit(f"{name}: 基幹 {kiban} + 専攻 {senkou} が卒業要件 {total} と合いません")
        c = {"id": cid, "name": name, "cls": cls, "total": total, "kiban": kiban, "senkou": senkou,
             "y1": y1, "groups": groups, "adv": ADV[cid]}
        if cid in DEPTS:
            c["totalRange"] = [min(grads), max(grads)]
        if cid in NOTES:
            c["note"] = NOTES[cid]
        out.append(c)
        print(f"{name}: 卒業 {total or c.get('totalRange')} / 基幹 {kiban} / 専攻 {senkou} / 1年次 {y1}")
    OUT.write_text(json.dumps({"source": SOURCE, "courses": out}, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"{OUT} に {len(out)} 件を書き出しました")


